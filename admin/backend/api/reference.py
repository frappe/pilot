from __future__ import annotations

import inspect
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import TYPE_CHECKING

from admin.backend.api.routes import API_V1_PREFIX

if TYPE_CHECKING:
    from werkzeug.routing import Rule

QUERY_PARAMETER = re.compile(r"request\.args\.get\(\s*[\"']([\w-]+)[\"']")
PATH_CONVERTER = re.compile(r"<(?:\w+:)?(\w+)>")
HEADER = """# Admin API reference

Generated by `pilot admin api-reference`. Do not edit it by hand. Run the command again after you add or change a route. See [Admin API](admin-api.md) for auth, the response shape, and errors.
"""


def get_api_reference() -> str:
    """The Admin API routes as Markdown: one table for each area, with methods, query parameters, and descriptions."""
    from flask import Flask

    from admin.backend.app import register_blueprints

    app = Flask("api-reference")
    register_blueprints(app)

    areas: dict[str, list[str]] = defaultdict(list)
    for rule in sorted(app.url_map.iter_rules(), key=lambda rule: rule.rule):
        if rule.rule.startswith(f"{API_V1_PREFIX}/"):
            path = PATH_CONVERTER.sub(r"<\1>", rule.rule.removeprefix(API_V1_PREFIX))
            areas[path.split("/")[1]].append(_row(rule, path, app.view_functions[rule.endpoint]))

    sections = [
        f"## {area}\n\n| Method | Path | Query | Description |\n| --- | --- | --- | --- |\n" + "\n".join(rows)
        for area, rows in sorted(areas.items())
    ]
    return "\n\n".join([HEADER.strip(), *sections]) + "\n"


def _row(rule: Rule, path: str, view) -> str:
    methods = ", ".join(sorted((rule.methods or set()) - {"HEAD", "OPTIONS"}))
    parameters = ", ".join(
        f"`{name}`" for name in dict.fromkeys(QUERY_PARAMETER.findall(inspect.getsource(view)))
    )
    description = (inspect.getdoc(view) or "").split("\n\n")[0].replace("\n", " ").replace("|", "\\|")
    return f"| {methods} | `{path}` | {parameters} | {description} |"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(get_api_reference(), encoding="utf-8")
