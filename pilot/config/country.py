def validate_country(country: str) -> str:
    """The country, or raise when Frappe does not know it."""
    if country not in COUNTRIES:
        raise ConfigError(f"Unknown country: {country!r}. Use a name such as {DEFAULT_COUNTRY!r}.")
    return country
